/** Stable, public error codes. Provider stack traces never cross this boundary. */
export type WhatsAppErrorCode =
  | 'WHATSAPP_INSTANCE_NOT_FOUND'
  | 'WHATSAPP_INSTANCE_NOT_CONNECTED'
  | 'WHATSAPP_INSTANCE_ALREADY_CONNECTED'
  | 'WHATSAPP_INSTANCE_LIMIT_REACHED'
  | 'WHATSAPP_INSTANCE_SUSPENDED'
  | 'WHATSAPP_QR_EXPIRED'
  | 'WHATSAPP_QR_NOT_AVAILABLE'
  | 'WHATSAPP_AUTH_INVALID'
  | 'WHATSAPP_LOGGED_OUT'
  | 'WHATSAPP_WORKER_OWNERSHIP_CONFLICT'
  | 'WHATSAPP_SEND_FAILED'
  | 'WHATSAPP_RATE_LIMITED'
  | 'WHATSAPP_UNSUPPORTED_MESSAGE'
  | 'WHATSAPP_INVALID_RECIPIENT'
  | 'WHATSAPP_MEDIA_TOO_LARGE'
  | 'WHATSAPP_MESSAGE_NOT_FOUND'
  | 'WHATSAPP_PAIRING_CODE_UNAVAILABLE'
  | 'VALIDATION_FAILED'
  | 'FORBIDDEN'
  | 'UNAUTHENTICATED'
  | 'SUBSCRIPTION_INACTIVE'
  | 'PLAN_LIMIT_REACHED'
  | 'FEATURE_NOT_IN_PLAN'
  | 'NOT_FOUND'
  | 'CONFLICT';

const HTTP_STATUS: Record<WhatsAppErrorCode, number> = {
  WHATSAPP_INSTANCE_NOT_FOUND: 404,
  WHATSAPP_MESSAGE_NOT_FOUND: 404,
  WHATSAPP_QR_NOT_AVAILABLE: 404,
  WHATSAPP_INSTANCE_NOT_CONNECTED: 409,
  WHATSAPP_INSTANCE_ALREADY_CONNECTED: 409,
  WHATSAPP_WORKER_OWNERSHIP_CONFLICT: 409,
  WHATSAPP_LOGGED_OUT: 409,
  WHATSAPP_AUTH_INVALID: 409,
  WHATSAPP_QR_EXPIRED: 410,
  WHATSAPP_INSTANCE_LIMIT_REACHED: 402,
  SUBSCRIPTION_INACTIVE: 402,
  WHATSAPP_INSTANCE_SUSPENDED: 423,
  WHATSAPP_RATE_LIMITED: 429,
  WHATSAPP_SEND_FAILED: 502,
  WHATSAPP_PAIRING_CODE_UNAVAILABLE: 504,
  WHATSAPP_UNSUPPORTED_MESSAGE: 422,
  WHATSAPP_INVALID_RECIPIENT: 422,
  WHATSAPP_MEDIA_TOO_LARGE: 413,
  VALIDATION_FAILED: 400,
  FORBIDDEN: 403,
  UNAUTHENTICATED: 401,
  PLAN_LIMIT_REACHED: 402,
  FEATURE_NOT_IN_PLAN: 402,
  NOT_FOUND: 404,
  CONFLICT: 409,
};

export class WhatsAppError extends Error {
  constructor(readonly code: WhatsAppErrorCode, message?: string, readonly retryable = false) {
    super(message ?? code);
    this.name = 'WhatsAppError';
  }
  get httpStatus(): number { return HTTP_STATUS[this.code]; }
}
